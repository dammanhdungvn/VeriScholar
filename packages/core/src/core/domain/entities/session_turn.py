"""SessionTurn Domain Entity.

Represents a single conversational exchange (turn) within a dual-chat research session.
Preserves user inquiry, grounded assistant response, verified citations, and token accounting.
"""

from datetime import UTC, datetime
from typing import Any
from uuid import UUID, uuid4

from pydantic import BaseModel, ConfigDict, Field

from core.domain.value_objects.enums import SessionTurnFinishReason


class SessionTurn(BaseModel):
    """Domain Entity representing a single dialogue turn in a research session."""

    model_config = ConfigDict(validate_assignment=True)

    id: UUID = Field(default_factory=uuid4, description="Unique turn identifier")
    session_id: UUID = Field(description="Parent research session identifier")
    turn_index: int = Field(ge=0, description="Sequential 0-indexed turn position in session")
    user_query: str = Field(min_length=1, description="Question asked by the researcher")
    assistant_response: str = Field(description="Response generated by the grounded AI assistant")
    citations: list[dict[str, Any]] = Field(
        default_factory=list,
        description="Structured citations containing chunk IDs, pages, and bounding boxes",
    )
    finish_reason: SessionTurnFinishReason = Field(
        default=SessionTurnFinishReason.STOP,
        description="Completion reason (e.g. stop, abstention, length)",
    )
    prompt_tokens: int = Field(default=0, ge=0, description="Tokens consumed by prompt")
    completion_tokens: int = Field(default=0, ge=0, description="Tokens generated by assistant")
    created_at: datetime = Field(default_factory=lambda: datetime.now(UTC))

    @property
    def total_tokens(self) -> int:
        """Total token footprint of this turn."""
        return self.prompt_tokens + self.completion_tokens

    @property
    def is_abstention(self) -> bool:
        """Check if assistant refused to answer due to insufficient evidence."""
        return self.finish_reason == SessionTurnFinishReason.ABSTENTION
